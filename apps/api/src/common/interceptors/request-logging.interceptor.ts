import {
  CallHandler,
  ExecutionContext,
  Injectable,
  Logger,
  NestInterceptor,
} from '@nestjs/common';
import type { Request, Response } from 'express';
import { Observable, tap } from 'rxjs';

/**
 * Ghi log metadata request tối thiểu (method, path, status, duration).
 * KHÔNG log headers nhạy cảm (Cookie, Authorization), API key, hay nội dung hội thoại.
 */
@Injectable()
export class RequestLoggingInterceptor implements NestInterceptor {
  private readonly logger = new Logger('HTTP');

  intercept(context: ExecutionContext, next: CallHandler): Observable<unknown> {
    const http = context.switchToHttp();
    const request = http.getRequest<Request>();
    const response = http.getResponse<Response>();
    const startedAt = Date.now();
    const pathOnly = request.originalUrl.split('?')[0];

    return next.handle().pipe(
      tap({
        next: () => {
          const durationMs = Date.now() - startedAt;
          this.logger.log(
            `${request.method} ${pathOnly} ${response.statusCode} ${durationMs}ms`,
          );
        },
      }),
    );
  }
}
